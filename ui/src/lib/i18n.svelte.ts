import { migrateClientStorage } from "./storage";

export type Locale = "en" | "pl";

const STORAGE_KEY = "orbitry.locale";

export const i18n = $state({
  locale: "en" as Locale,
});

export function detectLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "pl") return saved;
  } catch {
    // Private mode can block storage.
  }
  const lang =
    (typeof navigator !== "undefined" && (navigator.languages?.[0] || navigator.language)) || "en";
  return lang.toLowerCase().startsWith("pl") ? "pl" : "en";
}

export function initLocale() {
  migrateClientStorage();
  i18n.locale = detectLocale();
}

export function setLocale(locale: Locale) {
  i18n.locale = locale;
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    // Private mode can block storage.
  }
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const table = i18n.locale === "pl" ? pl : en;
  let text = table[key] ?? en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

